#!/usr/bin/env python3
"""Pre-project the world map into SVG paths: assets/data/worldmap.data.js.

The overview page draws a real world map (Equal Earth projection) shaded by each country's suicide
rate or indicator — with no mapping library and no network request, so it always loads.

  Shapes: Data/geo/countries-110m.json — world-atlas 2.0.2 (Natural Earth 1:110m, public domain)
  Codes:  Data/geo/codes.json — ISO 3166 alpha-2 / alpha-3 / numeric table, used to join the shapes
          (numeric ids) to the World Bank data (alpha-3 codes)

Run:   python3 tools/build_map.py
"""
import json
import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXTRA = {"Kosovo": "XKX"}  # not in ISO 3166 numeric; World Bank uses XKX
W, H = 960.0, 470.0


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx; y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring(arcs, idxs):
    pts = []
    for i in idxs:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a[1:] if pts else a)
    return pts


def fix_antimeridian(r):
    """Rings that cross the 180° meridian (eastern Russia, Fiji) would be drawn across the whole map.
    Unwrap them to continuous longitudes, then clamp to the dateline."""
    if not any(abs(b[0] - a[0]) > 180 for a, b in zip(r, r[1:])):
        return r
    return [(min(lon + 360 if lon < 0 else lon, 180.0), lat) for lon, lat in r]


def polygons(arcs, geom):
    if geom["type"] == "Polygon":
        return [[fix_antimeridian(ring(arcs, r)) for r in geom["arcs"]]]
    if geom["type"] == "MultiPolygon":
        return [[fix_antimeridian(ring(arcs, r)) for r in poly] for poly in geom["arcs"]]
    return []


# Equal Earth projection (Šavrič, Patterson & Jenny, 2018)
A1, A2, A3, A4 = 1.340264, -0.081106, 0.000893, 0.003796
M = math.sqrt(3) / 2


def equal_earth(lon, lat):
    lam, phi = math.radians(lon), math.radians(lat)
    th = math.asin(M * math.sin(phi))
    t2 = th * th; t6 = t2 ** 3
    x = lam * math.cos(th) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)))
    y = th * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))
    return x, y


def main():
    topo = json.loads((ROOT / "Data/geo/countries-110m.json").read_text())
    codes = {num: a3 for _, a3, num, *_ in json.loads((ROOT / "Data/geo/codes.json").read_text())}
    arcs = decode_arcs(topo)
    feats = []
    for g in topo["objects"]["countries"]["geometries"]:
        name = g["properties"]["name"]
        if name == "Antarctica":
            continue
        iso3 = codes.get(g.get("id")) or EXTRA.get(name)
        feats.append((iso3, name, [[[equal_earth(lon, lat) for lon, lat in r] for r in poly] for poly in polygons(arcs, g)]))
    xs = [x for _, _, ps in feats for p in ps for r in p for x, _ in r]
    ys = [y for _, _, ps in feats for p in ps for r in p for _, y in r]
    k = min(W / (max(xs) - min(xs)), H / (max(ys) - min(ys)))
    x0, y1 = min(xs), max(ys)
    countries = []
    for iso3, name, ps in feats:
        d = "".join("M" + "L".join(f"{(x - x0) * k:.1f},{(y1 - y) * k:.1f}" for x, y in r) + "Z" for p in ps for r in p)
        countries.append({"iso3": iso3, "name": name, "d": re.sub(r"\.0(?=[,LZ])", "", d)})
    out = {"viewBox": f"0 0 {W:.0f} {round((max(ys) - min(ys)) * k)}", "countries": countries}
    path = ROOT / "assets/data/worldmap.data.js"
    path.write_text("/* Generated by tools/build_map.py from world-atlas (Natural Earth) shapes — do not edit by hand. */\n"
                    f"window.WORLD_MAP = {json.dumps(out, separators=(',', ':'))};\n")
    data = json.loads(re.search(r"window\.MENTAL_DATA = (\{.*\});", (ROOT / "assets/data/mental.data.js").read_text(), re.S).group(1))
    have = {c["code"] for c in data["indicators"]["countries"] if c["v"][0] is not None}
    on_map = {c["iso3"] for c in countries}
    print(f"{path.relative_to(ROOT)}  {len(countries)} shapes  {path.stat().st_size // 1024} KB")
    print(f"countries with suicide data shown on the map: {len(have & on_map)} of {len(have)} (the rest are too small for a 1:110m map)")


if __name__ == "__main__":
    main()
